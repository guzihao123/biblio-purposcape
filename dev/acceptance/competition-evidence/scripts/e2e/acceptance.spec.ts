const diagnostics = new WeakMap<Page, Record<string, unknown>[]>

test.beforeEach(async ({ page }) => {
  await mkdir(RUN, { recursive: true })
  const events: Record<string, unknown>[] = []
  const completedRequests = new Set<string>()
  diagnostics.set(page, events)
  page.on('console', message => {
    if (message.type() === 'error') events.push({ type: 'console error', text: message.text(), url: message.location().url })
  })
  page.on('pageerror', error => events.push({ type: 'pageerror', text: error.message }))
  page.on('requestfinished', request => completedRequests.add(request.url()))
  page.on('requestfailed', request => events.push({
    type: 'requestfailed',
    method: request.method(),
    url: request.url(),
    error: request.failure()?.errorText,
    afterSuccessfulResponse: completedRequests.has(request.url()),
  }))
  page.on('response', response => {
    if (response.status() >= 400) events.push({ type: 'HTTP failure', status: response.status(), method: response.request().method(), url: response.url() })
  })
})

test.afterEach(async ({ page }, testInfo) => {
  const events = diagnostics.get(page) ?? []
  const destination = path.join(RUN, `${testInfo.title.split(' ')[0]}-browser-events.json`)
  await writeFile(destination, JSON.stringify(events, null, 2))
  await testInfo.attach('browser-events', { path: destination, contentType: 'application/json' })
  const unexpected = events.filter(event => !(
    event.type === 'requestfailed'
    && event.error === 'net::ERR_ABORTED'
    && event.afterSuccessfulResponse === true
  ))
  expect(unexpected, 'console error / pageerror / requestfailed / HTTP >=400 均不得出现').toEqual([])
})

