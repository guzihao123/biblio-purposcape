def connection_parameters():
    parameters = psycopg.conninfo.conninfo_to_dict(os.environ['DATABASE_URL'])
    parameters['connect_timeout'] = 10
    return parameters


def main():
    parameters = connection_parameters()
    with psycopg.connect(**parameters) as conn:
        with conn.cursor() as cur:
            cur.execute('SELECT rolcreaterole, rolsuper FROM pg_roles WHERE rolname = current_user')
            createrole, superuser = cur.fetchone()
            if not createrole:
                raise RuntimeError('migration_role_createrole_required')
            if not superuser:
                raise RuntimeError('migration_role_bypassrls_superuser_required')
            cur.execute('SELECT rolname FROM pg_roles WHERE rolname = ANY(%s)', (list(ROLE_NAMES),))
            if cur.fetchall():
                raise RuntimeError('test_roles_already_exist')
            cur.execute("SELECT count(*) FROM information_schema.tables WHERE table_schema='public'")
            if cur.fetchone()[0] != 0:
                raise RuntimeError('test_database_not_empty')

        schema_sql = (ROOT / 'sites' / 'schema.sql').read_text(encoding='utf-8')
        schema_sql = schema_sql.replace('BEGIN;', '').replace('COMMIT;', '')
        passwords = {name: secrets.token_urlsafe(32) for name in ROLE_NAMES}
        with conn.transaction():
            conn.execute(schema_sql)
            for name in ROLE_NAMES:
                conn.execute(
                    sql.SQL('CREATE ROLE {} LOGIN PASSWORD {}').format(
                        sql.Identifier(name),
                        sql.Literal(passwords[name]),
                    )
                )
            conn.execute('GRANT USAGE ON SCHEMA public TO app_user, app_admin, audit_reader')
            for table in TABLES:
                conn.execute(sql.SQL('GRANT SELECT, INSERT, UPDATE, DELETE ON {} TO app_user').format(sql.Identifier(table)))
                conn.execute(sql.SQL('GRANT SELECT ON {} TO audit_reader').format(sql.Identifier(table)))
            conn.execute('GRANT SELECT, INSERT, UPDATE, DELETE ON sites_skill_versions TO app_admin')
            conn.execute('GRANT SELECT ON sites_anonymous_sessions, sites_tasks TO app_admin')
            conn.execute('REVOKE UPDATE ON sites_anonymous_sessions FROM app_user')
            conn.execute('ALTER ROLE audit_reader BYPASSRLS')
            conn.execute(POLICY_SQL)

    ROLE_FILE.write_text(
        'APP_USER_PASSWORD=' + passwords['app_user'] + '\n'
        'APP_ADMIN_PASSWORD=' + passwords['app_admin'] + '\n'
        'AUDIT_READER_PASSWORD=' + passwords['audit_reader'] + '\n',
        encoding='utf-8',
    )
    ROLE_FILE.chmod(0o600)
    print(json.dumps({'migration': 'passed', 'tables': len(TABLES), 'roles': ROLE_NAMES, 'schema_changes_applied': True}, ensure_ascii=False))


if __name__ == '__main__':
    main()
